'''  单头自注意力
Self-Attention 做的是模糊匹配：Query 和每一个 Key 都会算出一个"相似度分数"
不是"取分数最高的那一行"，而是按分数比例，把所有 Value 加权混合在一起
'''
'''
Q、K、V ：三个可学习的矩阵
Q、K、V 不是三种不同的输入，它们都来自同一个词向量，只是被三个不同的权重矩阵分别投影了一次
Q = XW_q  , K = XW_k , V = XW_v
三个矩阵一开始是随机初始化的，训练过程中会不断调整
模型在训练中"学会"怎么提问（Q）、怎么被检索（K）、该交出什么信息（V）
'''